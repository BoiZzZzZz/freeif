// Copies the vault's ABI from the keeper, which generates it from the contract build.
// After a contract change: `forge build` in ../contracts, `pnpm abi` in ../keeper, then `pnpm abi` here.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(here, "../../keeper/src/abi.ts"), "utf8");
const out = source.replace(/^\/\/ Generated by.*\n/, "// Copied from keeper/src/abi.ts by scripts/copy-abi.mjs. Do not edit by hand: run `pnpm abi`.\n");
writeFileSync(join(here, "../src/lib/abi.ts"), out);
console.log(`src/lib/abi.ts written: ${out.length} characters`);
